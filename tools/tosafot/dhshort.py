_ABBR = sorted(ABBR, key=lambda x: -len(x[0].split()))
# "רבי X" פותח שם: ר' X (כמו בדפוס)
_RABI = re.compile(r'(?<![א-ת])רבי(?= [א-ת])')
_VAPREF = {'ו', 'ה'}


def plain(s):
    s = NIK.sub('', s or '').replace('־', ' ')
    return re.sub(r'\s+', ' ', s).strip()


def _abbr_phrase(words):
    """מחליף ביטויים מן המילון (גם עם תחילית ו/ד/ש/ה/ל/ב/כ/מ על המילה הראשונה בביטוי) ומחזיר רשימת מילים."""
    out, i = [], 0
    while i < len(words):
        hit = None
        for ph, ab in _ABBR:
            pw = ph.split()
            if words[i:i + len(pw)] == pw:
                hit = (len(pw), ab)
                break
        if hit:
            out.append(hit[1])
            i += hit[0]
        else:
            out.append(words[i])
            i += 1
    return out


def dh_words(dh):
    t = plain(dh)
    t = re.sub(r'^ד"ה\s+', '', t)
    t = re.sub(r"\s*וכו['׳]?\s*$", '', t).strip()
    t = t.replace("וכו'", '').replace('וכו׳', '').strip()
    t = _RABI.sub("ר'", t)
    return _abbr_phrase(t.split(' '))


def dh_short(dh, extra=0):
    """הד"ה המקוצר. extra = כמה מילים להוסיף (כשיש התנגשות באותו עמוד)."""
    w = [x for x in dh_words(dh) if x]
    if not w:
        return plain(dh)
    n = 2 + extra
    return ' '.join(w[:n])


def unique_shorts(items, key=lambda it: it['daf']):
    """items: רשימת dict עם dh ועם עמוד. מחזיר {id(item): dhs} כך שאין שני ד"ה זהים באותו עמוד."""
    by = {}
    for it in items:
        by.setdefault(key(it), []).append(it)
    out = {}
    for _, lst in by.items():
        extra = {id(it): 0 for it in lst}
        for _ in range(8):
            seen = {}
            for it in lst:
                seen.setdefault(dh_short(it['dh'], extra[id(it)]), []).append(it)
            clash = [v for v in seen.values() if len(v) > 1]
            if not clash:
                break
            for v in clash:
                for it in v:
                    if len(dh_words(it['dh'])) > 2 + extra[id(it)]:
                        extra[id(it)] += 1
        for it in lst:
            out[id(it)] = dh_short(it['dh'], extra[id(it)])
    return out


# ---- תיקון פיצול הד"ה: מקף צמוד למילה ("וכו' -בירושלמי", "ראשון- אין") הוא גבול ----
_TIGHT = re.compile(r"(?<=\S) -(?=\S)|(?<=\S)- (?=\S)")


def fix_dh_split(text, old_dh):
    """מחזיר (dh, כלל) לפי הכלל החדש, או (None, None) כשאין מקף צמוד בתוך 14 המילים הראשונות."""
    m = _TIGHT.search(text)
    sp = re.search(r' - ', text)
    if m and sp and sp.start() < m.start() and len(text[:sp.start()].split(' ')) <= 14:
        return None, None      # יש מקף רגיל קודם: הכלל הישן כבר מחתך נכון
    if m and len(text[:m.start()].split(' ')) <= 14:
        return text[:m.start()].strip(), 'מקף צמוד'
    return None, None
