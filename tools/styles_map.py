# ---------------------------------------------------------------- חציצה
# הכרעת בעל הפרויקט, 28.9.2026: "בכל מקום בכל מסכת היכן שיש שלוש כוכביות
# זה צריך לבוא בסגנון חציצה... שהכל יהיה אחיד". לכן התפקיד hatz אינו
# נגזר משם הסגנון בלבד: פסקה שכל תוכנה, אחרי הסרת רווחים רגילים, רווחים
# קשיחים וטאבים, הוא כוכביות בלבד - היא חציצה, יהא סגנונה אשר יהא.
# נמדד: 405 פסקאות כאלה ישבו בסגנונות גוף, נושא וד"ה, ובקידושין לבדה 212.
#
# באותה מידה, פסקה שכל תוכנה סימני-עיטור של גופני BA (התווים הלא-מוקצים
# U+05F5..U+05FF, שבהם 'BA Or Tzadikim' מצייר את קישוטיו) היא חציצה:
# הגופן אינו באתר, והלומד ראה במקומה ריבוע. אחידות גוברת.
STAR_CHARS = frozenset(chr(c) for c in (0x002a, 0x2217, 0x204e, 0x066d, 0x2731, 0xff0a))
ORNAMENT_CHARS = frozenset(chr(c) for c in range(0x05f5, 0x0600))
# רווח רגיל, רווח קשיח, טאב, סימני כיוון, ושבירות שורה
_HATZ_STRIP = str.maketrans('', '', ''.join(chr(c) for c in (0x20, 0xa0, 0x09, 0x200f, 0x200e, 0x0d, 0x0a)))


def hatz_kind(text):
    """'star' לפסקת כוכביות בלבד, 'orn' לפסקת עיטור בלבד, ואחרת None."""
    s = (text or '').translate(_HATZ_STRIP)
    if not s:
        return None
    cs = set(s)
    if cs <= STAR_CHARS:
        return 'star'
    if cs <= ORNAMENT_CHARS:
        return 'orn'
    return None


def role_of(block):
    """תפקיד הפסקה: מפת הסגנונות, ומעליה כלל החציצה. שני המסכים קוראים
    מכאן בלבד, כדי שפסקה תיפול לאותה יחידה בשני הצדדים."""
    if hatz_kind(block.get('text', '')):
        return 'hatz'
    return ROLE.get(block.get('style'), 'body')
