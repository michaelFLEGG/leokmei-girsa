# נגזר משם הסגנון בלבד: פסקה שכל תוכנה, אחרי הסרת רווחים רגילים, רווחים
# קשיחים וטאבים, הוא כוכביות בלבד - היא חציצה, יהא סגנונה אשר יהא.
# נמדד: 405 פסקאות כאלה ישבו בסגנונות גוף, נושא וד"ה, ובקידושין לבדה 212.
