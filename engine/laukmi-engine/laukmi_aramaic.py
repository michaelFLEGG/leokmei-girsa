# ============ ג. מורפולוגיה בטוחה ============
# רק תבניות שאין להן יוצא מן הכלל בקובץ. כל תבנית מובאת עם רשימת
# הפעלים שהיא חלה עליהם, ולא כתבנית פתוחה - תבנית פתוחה תופסת עברית.
MIGZAR = {"גז": "לגזוז", "כל": "לאכול", "זל": "לילך", "תני": "לשנות",
          "סר": "לאסור", "פרך": "להקשות", "כתב": "לכתוב", "תב": "לשבת",
          "עבד": "לעשות", "קם": "לקום", "נס": "ליטול"}
MORPH = [(r'(?<![א-ת"\'])(ו|ד|ל|ש|כ|ב)?למי' + re.escape(k) + r'(?![א-ת"\'])',
          lambda v=v: v) for k, v in MIGZAR.items()]

# ============ ד. גלאי הספק ============
# סימני היכר של ארמית. מילה שנושאת אחד מהם ואינה במילון - יוצאת לרשימת ההמתנה.
SIGNS = [r'ינן$', r'תא$', r'ייהו$', r'^קא[א-ת]{2,}', r'^אי[תצמ]',
         r'^למי', r'^דלי', r'^ניה', r'עידנא', r'פומ', r'ימר$', r'^מיח',
         r'^הוה$', r'^הוו$', r'^דהו', r'אנא$', r'^מיבע', r'^ליב', r'^ליח',
         r'^ניל', r'^נית', r'^ליכ', r'^ליט', r'^מיט', r'^איתי', r'^אית$']

# מילים שנושאות סימן ארמי אך המחבר משמר אותן בכוונה: מונחי סוגיה.
KEEP = {"הלכתא", "והלכתא", "והילכתא", "דאורייתא", "מדאורייתא", "בדאורייתא",
        "דרבנן", "ברייתא", "מתניתא", "במתניתא", "לישנא", "אסמכתא",
        "תיובתא", "ריעותא", "מילתא", "שמעתא", "שמעתתא", "פשיטא", "מיירי",
        "דמיירי", "לימא", "אימא", "ואימא", "איתמר", "אתמר", "מיתיבי",
        "איתיביה", "ואיתיביה", "והוינן", "הוינן", "בשלמא", "קשיא",
        "דיעבד", "מסקנא", "סוגיא", "גמרא", "משנה", "תוספתא", "דמי",
        "קמ\"ל", "מנלן", "דוקא", "אדרבה", "אטו", "איידי", "ואיידי"}


def suspects(path):
    """מפיק את המילים המסופקות: נראות ארמיות, אינן במילון ואינן מונחים."""
    from laukmi_scan import load, para_style, live_text, q
    z, doc, i2n = load(path)
    BODY = {"Normal", "רגיל", "פיסקת תשובה", "רווח לפני", "חלון 3"}
    rx = [re.compile(s) for s in SIGNS]
    known = set(LEXICON) | KEEP
    found = collections.Counter()
    ctx = collections.defaultdict(list)
    for p in doc.iter(q("p")):
        if para_style(p, i2n) not in BODY: continue
        t = re.sub(r"'[^']{0,200}'", " ", live_text(p))   # ציטוטים אינם ארמית
        for m in re.finditer(r"[א-ת]{3,}", t):
            w = m.group(0)
            if w in known: continue
            base = re.sub(r'^(ו|ד|ל|כ|מ|ש|ב|ה|וד|ול|וכ|דל)', '', w)
            if base in known or w in known: continue
            if any(r.search(w) for r in rx):
                found[w] += 1
                if len(ctx[w]) < 2:
                    ctx[w].append(t[max(0, m.start() - 35):m.end() + 30])
    return found, ctx


def todo(path, out):
    found, ctx = suspects(path)
    lines = ["# ארמית מסופקת - להכרעה בשלב המתקדם", "",
             f"{sum(found.values())} מופעים ב-{len(found)} צורות.",
             "כל אחת מהן נושאת סימן ארמי, אינה במילון הוודאי ואינה מונח שמור.",
             "**לא נגעתי באף אחת מהן.** ההכרעה היא מופע-מופע, כי חלקן עברית תקנית",
             "שנפלה בגלאי (ניקב · מראה · לילה) וחלקן ארמית שתרגומה תלוי הקשר.", ""]
    for w, n in found.most_common():
        lines.append(f"- **{w}** ({n})")
        for c in ctx[w]:
            lines.append(f"    - {c}")
    open(out, "w", encoding="utf-8").write("\n".join(lines))
    print(f"{sum(found.values())} מופעים ב-{len(found)} צורות -> {out}")


if __name__ == "__main__":
    todo(sys.argv[2], sys.argv[3] if len(sys.argv) > 3 else "aramaic_todo.md")
