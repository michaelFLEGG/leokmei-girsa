def heb(n):
    n = int(n)
    if n <= 10:
        return LET[n - 1]
    if n < 20:
        return 'י' + LET[n - 11]
    return 'כ' + (LET[n - 21] if n > 20 else '')


def short(t, n=90):
    t = NIK.sub('', t or '').strip()
    return t if len(t) <= n else t[:n].rsplit(' ', 1)[0] + '...'


