"""מקרה בדיקה לכפולות כמעט-זהות (פרומפט 44, 16.11.2026).

המקרה האמיתי (ברכות, משנה פרק א, יא.): קבלת סכם לפני תיקון פרומפט 43 העבירה את
"לקצר - אינו רשאי להאריך," לשורה הקודמת (תיקון נוסח ופיצול), אבל המחיקה מן השורה
הבאה ("לקצר- אינו רשאי להאריך,  לחתום...") לא אותרה ונשארה תלושה. בוורד נשארו
שתי שורות צמודות: השנייה היא הראשונה ועוד המשך. הבדיקה הישנה מצאה רק זהות מדויקת.

    python tools/test_near_dups.py
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ingest_repo as R


def blk(i, text, style='משניות'):
    return {'i': i, 'style': style, 'text': text}


def main():
    # המקרה של ברכות: הכלה, ברווח ובמקף שונים
    b = [blk(0, 'לקצר - אינו רשאי להאריך,'),
         blk(1, ' לקצר- אינו רשאי להאריך,  לחתום א"י שלא לחתום, שלא לחתום א"י לחתום.')]
    assert list(R.near_dups(b)) == [(0, 1, 'prefix')], list(R.near_dups(b))
    # זהות אחרי נרמול (ניקוד, גרשיים, פיסוק בקצה)
    b = [blk(0, 'ואין לי אלא שקרא שמו \'עשירי\','), blk(1, 'ואין לי אלא שקרא שמו עשירי,')]
    assert [k for _, _, k in R.near_dups(b)] == ['same']
    # ציון דף, מספור, ושורת דובר קצרה: אינם כפולה
    for a, c in (('מ.', 'מ:'), ('ב.', 'ב.'), ('ה"ק:', 'ה"ק:')):
        assert not list(R.near_dups([blk(0, a), blk(1, c)])), (a, c)
    # כותרת ואחריה גוף שפותח באותן מילים (סגנון שונה): דרך הדף, לא כפולה
    b = [blk(0, 'מאימתי קורין את שמע', 'נושא'), blk(1, 'מאימתי קורין את שמע בערבית', 'Normal')]
    assert not list(R.near_dups(b))
    # שתי שורות שונות מעבר להתחלה (לא הכלה): אינן כפולה
    b = [blk(0, 'ר"א אומר עד שיעלה'), blk(1, 'ר"א אומר עד חצות')]
    assert not list(R.near_dups(b))
    # חיתוך באמצע מילה אינו התחלה מלאה
    b = [blk(0, 'אחת ארוכה ואחת קצ'), blk(1, 'אחת ארוכה ואחת קצרה.')]
    assert not list(R.near_dups(b))
    print('עבר: 6 מקרים')


if __name__ == '__main__':
    main()
