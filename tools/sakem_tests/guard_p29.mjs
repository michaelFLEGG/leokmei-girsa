/* פרומפט 29 (9.11.2026): מבחן מקומי לכללים החדשים של הבודק במצב המשימה (בלי רשת, בלי מודל).
   node tools/sakem_tests/guard_p29.mjs - קוד יציאה 1 אם מבחן נכשל */
import { createRequire } from 'node:module';
const SKC = createRequire(import.meta.url)('../sakem_core.js');
let bad = 0;
const ok = (name, c) => { console.log((c ? 'עבר  ' : 'נכשל ') + name); if (!c) bad++; };
const has = (r, re) => r.errs.some((e) => re.test(e));
const G = 'שורה של גמרא רגילה שאין בה כלום מיוחד.';
// א. עיטור
ok('עיטור לפני [משנה] - צמוד', SKC.hatzNearHead('[קבוע:9]\n[מקור:2a.1]\n[משנה:ב]\nלשון המשנה', 9));
ok('עיטור אחרי שורת משנה בתיבה - צמוד', SKC.hatzNearHead('[משנה]\nלשון המשנה\n[קבוע:9]\n[גמרא]\n' + G, 9));
ok('עיטור לפני שורת (משנה) - צמוד', SKC.hatzNearHead(G + '\n[קבוע:9]\n(משנה) מעשה והביאו\n[משנה]\nלשון', 9));
ok('עיטור לפני ד"ה משנה בשורה - צמוד', SKC.hatzNearHead(G + '\n[קבוע:9]\n{דה:המוכר} - כך וכך', 9));
ok('עיטור אחרי פתיחת פרק - צמוד (heads)', SKC.hatzNearHead('[קבוע:5]\n[קבוע:9]\n' + G, 9, { heads: [5] }));
ok('עיטור בין שתי שורות גמרא - אינו צמוד', !SKC.hatzNearHead(G + '\n[קבוע:9]\n' + G, 9));
const t1 = '[קבוע:9]\n[משנה:א]\n{ב:לשון} המשנה';
ok('עיטור צמוד שלא נמחק - חוסם במשימה', has(SKC.comply(t1, t1, { strict: true, hatz: [9] }), /עיטור 9/));
ok('ובשרת (בלי strict) - אזהרה בלבד', !has(SKC.comply(t1, t1, { hatz: [9] }), /עיטור 9/));
// ב. מקף תירוץ
const k = '[צד:וקשה:]\nוהרי אמרו שמותר?\nכאן מדובר בשאר מינים, ולכן אין קושיה.';
ok('מקף תירוץ חסר - חוסם', has(SKC.comply(k, k, { strict: true }), /מקף תירוץ/));
ok('נימוק ב-keep פוטר', !has(SKC.comply(k, k, { strict: true, keep: ['כאן מדובר בשאר - זו עוד שאלה ולא תשובה'] }), /מקף תירוץ/));
ok('תשובה בסגנון (תשובה) - אינה חסרה', !has(SKC.comply(k.replace('כאן מדובר', '(תשובה) כאן מדובר'), k.replace('כאן מדובר', '(תשובה) כאן מדובר'), { strict: true }), /מקף/));
ok('שורת המשך (אחרי נקודתיים) אינה התירוץ', !has(SKC.comply('[צד:וקשה:]\nוהרי דרש:\nכארז - שגזעו מחליף!\n(תשובה) כאן בשאר.', '[צד:וקשה:]\nוהרי דרש:\nכארז - שגזעו מחליף!\n(תשובה) כאן בשאר.', { strict: true }), /מקף/));
// ג. שורה אלמנה
const long = Array(13).fill('אמר').join(' ') + ' ומשמעויותיהם';
ok('שורה אלמנה בשורה ששונתה - חוסם', has(SKC.comply(G, long, { strict: true, }), /אלמנה/));
ok('שורה אלמנה שלא נגעו בה - אינה חוסמת', !has(SKC.comply(long, long, { strict: true }), /אלמנה/));
// ד. כותרת צד
ok('כותרת צד חדשה של שלוש מילים - חוסם', has(SKC.comply('[צד:רבא:]\n' + G, '[צד:רב יהודה מרב:]\n' + G, { strict: true }), /כותרת צד של 3/));
ok('מספור (יב.) אינו נספר', !has(SKC.comply('[צד:רבא:]\n' + G, '[צד:יב. ר\' יוחנן:]\n' + G, { strict: true }), /כותרת צד של/));
// ה. ראשי תיבות
const ab = SKC.abbrOpen('[צד:ר"ש:]\n' + G, '[צד:רבי שמעון בן יוחאי:]\n' + G);
ok('פתיחת ר"ת בכותרת צד שיוצאת ארוכה - פסולה', ab.length && ab.some((x) => x.bad));
const ab2 = SKC.abbrOpen('אמר ר"ש הכי.', 'אמר רב ששת הכי.');
ok('פתיחה קצרה בשורה - מותרת, עם אזהרה', ab2.length === 1 && !ab2[0].bad);
// ו. רווח לכל קטע
ok('קטע עם פתיחת יחידה בלי כותרת ובלי רווח - חוסם', has(SKC.comply(G + '\n' + G, G + '\n' + G, { strict: true, unitOpen: 1 }), /אין אף \(רווח\)/));
ok('ועם (רווח) - עובר', !has(SKC.comply(G + '\n(רווח) ' + G, G + '\n(רווח) ' + G, { strict: true, unitOpen: 1 }), /רווח/));
console.log(bad ? bad + ' מבחנים נכשלו' : 'הכל עבר');
process.exit(bad ? 1 : 0);
